function getLang() {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved && STRINGS[saved]) return saved;
  } catch {}
  return (navigator.language || "").toLowerCase().startsWith("ko") ? "ko" : "en";
}

function setLang(lang) {
  try { localStorage.setItem(LANG_KEY, lang); } catch {}
}

/** Translated string. {name} placeholders are filled from vars
 *  번역 문자열. {name} 자리에 vars 값을 넣는다 */
function t(key, vars = {}) {
  const lang = getLang();
  const s = STRINGS[lang][key] ?? STRINGS.ko[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? vars[k] : `{${k}}`));
}

/** Fill data-i18n (text) · data-i18n-html (HTML from the dictionary) · data-i18n-placeholder
 *  data-i18n(텍스트) · data-i18n-html(사전에 있는 HTML) · data-i18n-placeholder 를 채운다 */
function applyI18n(root = document) {
  document.documentElement.lang = getLang();
  root.querySelectorAll("[data-i18n]").forEach((el) => (el.textContent = t(el.dataset.i18n)));
  root.querySelectorAll("[data-i18n-html]").forEach((el) => (el.innerHTML = t(el.dataset.i18nHtml)));
  root.querySelectorAll("[data-i18n-placeholder]").forEach((el) => (el.placeholder = t(el.dataset.i18nPlaceholder)));
  root.querySelectorAll("[data-i18n-title]").forEach((el) => (el.title = el.ariaLabel = t(el.dataset.i18nTitle)));
}
